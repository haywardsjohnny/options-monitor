def main(argv=None):
    parser = argparse.ArgumentParser(description='Options Flow Monitor - E2E')
    parser.add_argument('--init', action='store_true', help='Generate requirements, Dockerfile, .env.sample and README')
    parser.add_argument('--run', action='store_true', help='Run monitor once and exit')
    parser.add_argument('--daemon', action='store_true', help='Run as background scheduler polling every POLL_INTERVAL_MIN minutes')
    parser.add_argument('--symbols', type=str, help='Comma-separated symbols to monitor (overrides .env SYMBOLS)')
    args = parser.parse_args(argv)

    if args.init:
        generate_supporting_files(output_dir='.')
        print('Init files generated (requirements.txt, Dockerfile, .env.sample, README.md)')
        return

    if args.symbols:
        symbols = [s.strip().upper() for s in args.symbols.split(',') if s.strip()]
    else:
        symbols = SYMBOLS

    init_db(DB_PATH)

    if args.run:
        monitor_once(symbols)
        return

    if args.daemon:
        # Use APScheduler to run monitor periodically in background
        executors = {
            'default': {'type': 'threadpool', 'max_workers': 5},
            'processpool': ProcessPoolExecutor(max_workers=2)
        }
        scheduler = BackgroundScheduler(executors=executors, timezone='US/Eastern')
        scheduler.add_job(lambda: monitor_once(symbols), 'interval', minutes=POLL_INTERVAL_MIN, next_run_time=datetime.now())
        scheduler.start()
        logger.info('Scheduler started: polling every %s minutes for symbols: %s', POLL_INTERVAL_MIN, symbols)
        try:
            while True:
                time.sleep(10)
        except (KeyboardInterrupt, SystemExit):
            scheduler.shutdown()
            logger.info('Scheduler stopped')
        return

    # Default action: run once
    monitor_once(symbols)

if __name__ == '__main__':
    main()
