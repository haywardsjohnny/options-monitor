"""
Options Flow Monitor - End-to-end Python agent

What this file contains
- A single-file end-to-end solution you can run locally or in Docker.
- Connects to a third-party options trade API (Polygon.io example implemented).
- Runs a rule-based suspicious-trade detector (10 rules you specified).
- Schedules checks at fixed intervals (default 30 minutes) using APScheduler.
- Persists results to SQLite and saves CSVs for flagged trades.
- Sends alerts via Slack webhook (optional) and writes logs.
- Helper to generate Dockerfile, requirements.txt, and sample .env file.

How to use
1) Create a directory and put this file there.
2) Create a .env file (see sample generated by --init or look at README below):
   - POLYGON_API_KEY=...
   - PROVIDER=polygon    # or tradier (placeholders)
   - SYMBOLS=ORCL,NBIS,AAPL
   - POLL_INTERVAL_MIN=30
   - SLACK_WEBHOOK_URL=...
   - ALERT_THRESHOLD=2   # suspicious score threshold to alert
3) Install requirements:
   pip install -r requirements.txt
   (or run: python options-flow-monitor-e2e.py --init to create files)
4) Run:
   python options-flow-monitor-e2e.py

Notes
- Polygon API endpoint /v3/trades/options/{symbol} is used as example; adapt if your provider differs.
- This script is ready-to-run but will need your API key and webhook.

"""

